// Барселона не считается чужим городом, даже если рядом назван другой («из Парижа в Барселону»).
const HOME = /(?<![\p{L}])(барселон|barcelon|барса(?![\p{L}])|bcn)/u

function normalize(s: string): string {
  return s.toLowerCase().replace(/ё/g, 'е').replace(/[-–—]/g, ' ')
}

const PATTERNS = Object.entries(CITIES).map(([city, stems]) => {
  const alt = stems
    .map((stem) => {
      const tail = /[a-z]/.test(stem) ? '{0,1}' : '{0,3}'
      return `${stem.replace(/ /g, '\\s+')}\\p{L}${tail}`
    })
    .join('|')
  return { city, re: new RegExp(`(?<![\\p{L}])(?:${alt})(?![\\p{L}])`, 'u') }
})

// Название города из словаря, найденного в запросе, либо null (и для Барселоны, и если города нет).
export function findForeignCity(text: string): string | null {
  const t = normalize(text)
  if (HOME.test(t)) return null
  return PATTERNS.find((p) => p.re.test(t))?.city ?? null
}
